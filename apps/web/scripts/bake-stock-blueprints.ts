/**
 * Bakes stock's blueprints (ADR 0316): builds every source of `src/lib/editor/blueprint-sources.ts`
 * against stock's content with the Hangar editor's operations, and writes the designs into
 * `mods/stock/src/blueprints.generated.ts`, which stock registers. Run after changing a builder:
 *
 *   bun scripts/bake-stock-blueprints.ts
 */
import { loadPlugins } from '@orbital/core';
import Stock from '@orbital/mod-stock';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { bakeStockBlueprints } from '../src/lib/editor/blueprint-sources';

const { registries } = loadPlugins([Stock]);
const baked = bakeStockBlueprints({ parts: registries.parts, modules: registries.modules });
const file = join(import.meta.dir, '../../../mods/stock/src/blueprints.generated.ts');
writeFileSync(
	file,
	`// Generated by apps/web/scripts/bake-stock-blueprints.ts (ADR 0316). Do not edit: change the builder, then bake.
import type { BlueprintDefinition } from '@orbital/sdk';

const DATA: unknown = ${JSON.stringify(baked, null, '\t')};

/** The learn examples and the famous missions, in Library order. */
export const STOCK_BLUEPRINTS = DATA as readonly BlueprintDefinition[];
`
);
// the repository's formatting, so a bake with no builder change leaves no diff
Bun.spawnSync(['bunx', 'prettier', '--write', file], { cwd: join(import.meta.dir, '..') });
console.log(`wrote ${baked.length} blueprints to ${file}`);
