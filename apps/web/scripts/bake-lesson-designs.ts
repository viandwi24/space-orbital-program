/**
 * Bakes the lessons' vessels and the stock system's numbers (plan 379, ADR 0355): builds every
 * vessel of `src/lib/onboarding/lesson-vessels.ts` against stock's content with the Hangar editor's
 * operations, and computes the Δv and orbit the lesson texts quote, into
 * `mods/stock/src/lessons/designs.generated.ts`, which stock's lessons import. Run after changing a
 * lesson vessel:
 *
 *   bun scripts/bake-lesson-designs.ts
 */
import { loadPlugins } from '@orbital/core';
import Stock, { HomeBody, MoonBody, SunBody } from '@orbital/mod-stock';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { bakeLessonDesigns, lessonFacts } from '../src/lib/onboarding/lesson-bake';

const { registries } = loadPlugins([Stock]);
const designs = bakeLessonDesigns({ parts: registries.parts, modules: registries.modules });
const facts = lessonFacts([SunBody, HomeBody, MoonBody]);
const file = join(import.meta.dir, '../../../mods/stock/src/lessons/designs.generated.ts');
writeFileSync(
	file,
	`// Generated by apps/web/scripts/bake-lesson-designs.ts (ADR 0355). Do not edit: change the vessel, then bake.
import type { VesselDesign } from '@orbital/sdk';

const DATA: unknown = ${JSON.stringify(designs, null, '\t')};

/** The lessons' vessels by name. */
export const DESIGNS = DATA as Record<
	'skylark' | 'pathfinderCapsule' | 'pathfinder' | 'lander' | 'chaser' | 'beacon' | 'relayProbe' | 'relaySatellite' | 'arm' | 'spentStage' | 'moonBase',
	VesselDesign
>;

/** What the stock system asks of a rocket, as the lesson texts quote it. */
export const LESSON_FACTS = ${JSON.stringify(facts)} as { lowOrbit: number; dvToOrbit: number };
`
);
Bun.spawnSync(['bunx', 'prettier', '--write', file], { cwd: join(import.meta.dir, '..') });
console.log(`wrote ${Object.keys(designs).length} lesson vessels to ${file}`);
