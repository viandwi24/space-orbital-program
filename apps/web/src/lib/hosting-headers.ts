/**
 * The response headers a host should send for the static build (plan 023, ADR 0040, ADR 0038,
 * `architecture/hosting.md`). Pure: the serve script (`scripts/serve.ts`) and the tests use it, and
 * the documentation prints its output. A static host cannot compute the inline-script hashes, so
 * the script derives them from the built HTML.
 */

/** `sha256-<base64>` of `text` as a CSP source (the same form as in the sandbox document). */
export async function sha256Source(text: string): Promise<string> {
	const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
	let binary = '';
	for (const byte of new Uint8Array(digest)) binary += String.fromCharCode(byte);
	return `sha256-${btoa(binary)}`;
}

/** The text of every inline `<script>` (no `src`) in an HTML document. */
export function inlineScripts(html: string): string[] {
	const out: string[] = [];
	for (const m of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)) {
		if (m[1] !== undefined && m[1].trim() !== '') out.push(m[1]);
	}
	return out;
}

/**
 * The Content-Security-Policy of a game page. `inline` are the hashes of the page's own inline
 * scripts (the SvelteKit bootstrap) and of the script sandbox bootstrap (a srcdoc iframe inherits
 * the page's policy as well as its own, ADR 0038). `blob:` is for mod packages (ADR 0057: a mod is
 * imported from a blob URL) and the sandbox's blob Worker; `connect-src https:` lets the player
 * download a mod package from an address they type. `style-src 'unsafe-inline'` is for the inline
 * styles Svelte and the canvas widgets set.
 */
export function contentSecurityPolicy(inline: readonly string[]): string {
	const hashes = inline.map((h) => `'${h}'`).join(' ');
	return [
		"default-src 'self'",
		`script-src 'self' 'wasm-unsafe-eval' blob: ${hashes}`.trim(),
		"style-src 'self' 'unsafe-inline'",
		"img-src 'self' data: blob:",
		"font-src 'self'",
		"connect-src 'self' https: blob: data:",
		"worker-src 'self' blob:",
		'frame-src about:',
		"object-src 'none'",
		"base-uri 'self'",
		"form-action 'self'",
		"frame-ancestors 'self'"
	].join('; ');
}

/** Headers for every response; `csp` only for HTML documents. */
export function securityHeaders(): Record<string, string> {
	return {
		'X-Content-Type-Options': 'nosniff',
		'Referrer-Policy': 'no-referrer',
		'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=()',
		'Cross-Origin-Opener-Policy': 'same-origin'
	};
}

/** Cache policy by path: hashed assets for a year, everything else revalidated. */
export function cacheControl(pathname: string): string {
	return pathname.startsWith('/_app/immutable/')
		? 'public, max-age=31536000, immutable'
		: 'no-cache';
}

/**
 * The paths whose responses are not documents (plan 202): a `_headers` file takes the policy off
 * them, since a host joins every rule that matches into one header and a policy on a script or a
 * worker would apply to it as well. `scripts/serve.ts` sends the policy only with HTML.
 */
export const NON_DOCUMENT_PATHS = [
	'/_app/*',
	'/basis/*',
	'/ephemeris/*',
	'/sandbox/*.js',
	'/*.png',
	'/*.jpg',
	'/*.txt'
] as const;

/**
 * A `_headers` file (Cloudflare Pages, Netlify) for the build (plan 202): the security headers and
 * the one policy for every page (`policy`, from `scripts/site-policy.ts`), taken off the assets,
 * and a year of caching for hashed assets. The other paths keep the host's revalidating default.
 */
export function headersFile(policy: string): string {
	const lines = ['# Generated by apps/web/scripts/emit-headers.ts (plan 202). Do not edit.', '/*'];
	for (const [name, value] of Object.entries(securityHeaders())) lines.push(`  ${name}: ${value}`);
	lines.push(`  Content-Security-Policy: ${policy}`);
	for (const path of NON_DOCUMENT_PATHS) lines.push('', path, '  ! Content-Security-Policy');
	lines.push('', '/_app/immutable/*', `  Cache-Control: ${cacheControl('/_app/immutable/')}`);
	return `${lines.join('\n')}\n`;
}

/**
 * The policy as a `<meta>` can carry it (GitHub Pages sends no headers): without `frame-ancestors`,
 * which a meta policy ignores, so another site may frame the game there (`architecture/hosting.md`).
 */
export function metaPolicy(policy: string): string {
	return policy
		.split('; ')
		.filter((d) => !d.startsWith('frame-ancestors'))
		.join('; ');
}

/** `html` with the meta policy as the first element after `<meta charset>`, before any script. */
export function injectMetaCsp(html: string, policy: string): string {
	if (html.includes('http-equiv="Content-Security-Policy"')) return html;
	const content = metaPolicy(policy).replaceAll('&', '&amp;').replaceAll('"', '&quot;');
	const tag = `<meta http-equiv="Content-Security-Policy" content="${content}" />`;
	const charset = html.match(/<meta charset="[^"]*"\s*\/?>/i);
	if (charset?.index !== undefined) {
		const at = charset.index + charset[0].length;
		return `${html.slice(0, at)}\n\t\t${tag}${html.slice(at)}`;
	}
	return html.replace(/<head>/i, `<head>\n\t\t${tag}`);
}
