/**
 * The crew API sample (plan 375, ADR 0313): what a mod can add to the crew without touching the
 * game. Every piece is optional; delete what you do not need.
 */
import {
	defineCrewAnimation,
	defineCrewExpression,
	defineCrewOutfit,
	defineCrewPortrait,
	definePatch,
	definePlugin
} from '@orbital/sdk';

/** A marching-band jacket. `uses: ['hangar']` puts it on some of the Hangar's walkers. */
export const Band = defineCrewOutfit({
	id: 'crew-sample.band',
	title: 'Marching band',
	body: 'coat',
	suit: 0xb3202a,
	trim: 0xf2c94c,
	accent: 0xf2c94c,
	legs: 0x1d2333,
	boots: 0x111318,
	gloves: 0xf6f3ea,
	headwear: 'cap',
	headwearColour: 0xb3202a,
	eyewear: 'none',
	prop: 'none',
	pack: 'none',
	harness: true,
	uses: ['hangar', 'space-center', 'lineup']
});

/**
 * A high-stepping march as keyframes: the legs swing far, the arms opposite. A keyframed `walk`
 * spans one stride (0.84 m), so the feet still keep pace with the ground. Registered after stock,
 * it is the walk every walker uses.
 */
export const March = defineCrewAnimation({
	id: 'crew-sample.march',
	title: 'March',
	role: 'walk',
	keys: [
		{
			t: 0,
			pose: { legLPitch: 0.9, legRPitch: -0.35, armLPitch: -0.6, armRPitch: 0.6, bob: 0.03 }
		},
		{
			t: 0.5,
			pose: { legLPitch: -0.35, legRPitch: 0.9, armLPitch: 0.6, armRPitch: -0.6, bob: 0.03 }
		}
	],
	duration: 1
});

/** Both arms up, as a pure function of time instead of keyframes. */
export const Cheer = defineCrewAnimation({
	id: 'crew-sample.cheer',
	title: 'Cheer',
	role: 'wave',
	pose: (t, { seed }) => ({
		armLRaise: 2.6 + Math.sin(t * 6 + seed) * 0.2,
		armRRaise: 2.6 + Math.sin(t * 6 + seed + 1) * 0.2,
		bob: Math.abs(Math.sin(t * 6 + seed)) * 0.04,
		headPitch: -0.15
	})
});

/** Wide eyes and a grin; it answers no mood, so the game never picks it on its own. */
export const StarEyed = defineCrewExpression({
	id: 'crew-sample.star-eyed',
	title: 'Star-eyed',
	eyes: { left: 'wide', right: 'wide' },
	brows: { tilt: [0.2, 0.2], lift: 0.02 },
	mouth: 'grin'
});

/** A portrait image (an asset of this package, generated by `assets.ts`) for the band outfit. */
export const BandFace = defineCrewPortrait({
	id: 'crew-sample.band-face',
	title: 'Band portrait',
	image: 'portraits/band.png',
	outfit: 'crew-sample.band'
});

/** Stock's mechanics in teal: a patch changes another plugin's outfit without replacing it. */
export const TealMechanics = definePatch({
	id: 'crew-sample.teal-mechanics',
	target: 'crew-outfit',
	select: { id: 'stock.mechanic' },
	ops: [
		{ op: 'set', path: 'suit', value: 0x1f8a8a },
		{ op: 'set', path: 'legs', value: 0x1f8a8a }
	]
});

export default definePlugin({
	meta: {
		id: 'crew-sample',
		version: '1.0.0',
		api: '^0.1.111',
		title: 'Marching band (crew sample)'
	},
	depends: ['stock'],
	setup(ctx) {
		ctx.crewOutfits.register(Band);
		ctx.crewAnimations.register(March);
		ctx.crewAnimations.register(Cheer);
		ctx.crewExpressions.register(StarEyed);
		ctx.crewPortraits.register(BandFace);
		ctx.patches.register(TealMechanics);
	}
});
